import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {seedLeads,seedQuotes,seedOrders,seedTeam} from './fixtures/auto-sale-business.mjs';

test('manager quote uses new US invoice + TKS inputs, age and RUB converter',async()=>{
 const dom=new JSDOM('<!doctype html><div id="app"></div>',{url:'https://auto-sale.viiversion.com/'});
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,sessionStorage:dom.window.sessionStorage,FormData:dom.window.FormData,Event:dom.window.Event,CustomEvent:dom.window.CustomEvent});
 localStorage.setItem('auto-sale-leads-v2',JSON.stringify(seedLeads()));
 localStorage.setItem('auto-sale-quotes-v2',JSON.stringify(seedQuotes()));
 localStorage.setItem('auto-sale-orders-v2',JSON.stringify(seedOrders()));
 localStorage.setItem('auto-sale-team-v1',JSON.stringify(seedTeam()));
 await import('../public/auto-sale-app-v3.mjs?quoteAuditUI='+Date.now());
 const root=document.querySelector('#app');
 root.querySelector('[data-role="manager"]').click();
 root.querySelector('[data-go="quotes"]').click();
 root.querySelector('[data-new-quote]').click();
 const f=root.querySelector('#quoteForm');
 assert.ok(f);assert.ok(f.elements.manufactureDate);assert.ok(f.elements.invoiceUsd);assert.ok(f.elements.customsRub);
 assert.match(root.querySelector('#quoteForm').textContent,/Таможенная оценка и утильсбор/);
 f.elements.origin.value='США';
 f.elements.origin.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
 f.elements.manufactureDate.value='2024-01';
 f.elements.manufactureDate.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
 assert.equal(f.elements.ageCategory.value,'under3');
 assert.equal(f.elements.legalization.value,'6000');
 assert.equal(f.elements.service.value,'500');
 assert.equal(f.elements.partsCountry.value,'Грузия');
 assert.equal(f.elements.repairCountry.value,'Россия');
 f.elements.lot.value='10000';
 f.elements.usdRubRate.value='90';
 f.elements.usdRubRate.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 f.elements.customsRub.value='90000';
 f.elements.customsRub.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 f.elements.recyclingRub.value='45000';
 f.elements.recyclingRub.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 assert.equal(Number(f.elements.customs.value),1000);
 assert.equal(Number(f.elements.recyclingFee.value),500);
 assert.match(root.querySelector('#quoteCostPreview').textContent,/себестоимость/i);
 f.elements.customsConfirmed.checked=true;
 f.elements.customsRub.value='99000';
 f.elements.customsRub.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 assert.equal(f.elements.customsConfirmed.checked,false);
 dom.window.close();
});
