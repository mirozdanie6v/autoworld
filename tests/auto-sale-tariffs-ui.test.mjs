import test from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {seedLeads,seedQuotes,seedOrders,seedTeam} from './fixtures/auto-sale-business.mjs';
const tick=()=>new Promise(r=>setTimeout(r,0));
test('new USA quote auto-fills included service and blocks incomplete fees until manager confirms',async()=>{
 const dom=new JSDOM('<!doctype html><div id="app"></div>',{url:'https://auto-sale.viiversion.com/'});
 Object.assign(globalThis,{window:dom.window,document:dom.window.document,localStorage:dom.window.localStorage,sessionStorage:dom.window.sessionStorage,FormData:dom.window.FormData,Event:dom.window.Event,CustomEvent:dom.window.CustomEvent});
 localStorage.setItem('auto-sale-leads-v2',JSON.stringify(seedLeads()));
 localStorage.setItem('auto-sale-quotes-v2',JSON.stringify(seedQuotes()));
 localStorage.setItem('auto-sale-orders-v2',JSON.stringify(seedOrders()));
 localStorage.setItem('auto-sale-team-v1',JSON.stringify(seedTeam()));
 await import('../public/auto-sale-app-v3.mjs?tariff-ui='+Date.now());
 const root=document.querySelector('#app');
 root.querySelector('[data-role="manager"]').click();
 root.querySelector('[data-go="quotes"]').click();
 root.querySelector('[data-new-quote]').click();
 let form=root.querySelector('#quoteForm');
 assert.ok(form);
 form.elements.origin.value='США';
 form.elements.origin.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
 form.elements.ageCategory.value='3to5';
 form.elements.ageCategory.dispatchEvent(new dom.window.Event('change',{bubbles:true}));
 assert.equal(Number(form.elements.legalization.value),4500);
 assert.equal(Number(form.elements.service.value),500);
 assert.equal(Number(form.elements.ocean.value),3350);
 form.elements.model.value='Test US 2022';
 form.elements.engineCc.value='2000';form.elements.powerHp.value='150';form.elements.engineType.value='petrol';form.elements.importerType.value='nat';form.elements.priceSource.value='Copart';form.elements.customsSource.value='TKS';form.elements.customsCheckedAt.value='2026-10-20';
 form.elements.lot.value='10000';form.elements.auction.value='800';form.elements.inland.value='400';
 form.elements.lot.dispatchEvent(new dom.window.Event('input',{bubbles:true}));
 assert.equal(Number(form.elements.cryptoFee.value),392);
 form.elements.customs.value='4000';form.elements.recyclingFee.value='500';form.elements.repair.value='1200';
 form.elements.validUntil.value='2026-11-10';
 form.elements.status.value='Отправлен';
 form.dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
 await tick();
 assert.ok(root.querySelector('#quoteForm'),'without confirmation the draft must remain open');
 assert.equal(JSON.parse(localStorage.getItem('auto-sale-quotes-v2')).some(q=>q.model==='Test US 2022'),false);
 form=root.querySelector('#quoteForm');
 for(const name of ['customsConfirmed','recyclingConfirmed','repairReviewed','cryptoBaseConfirmed'])form.elements[name].checked=true;
 form.dispatchEvent(new dom.window.Event('submit',{bubbles:true,cancelable:true}));
 await tick();
 const q=JSON.parse(localStorage.getItem('auto-sale-quotes-v2')).find(q=>q.model==='Test US 2022');
 assert.ok(q);
 assert.equal(q.status,'Отправлен');
 assert.equal(q.service,500);assert.equal(q.legalization,4500);
 assert.equal(q.cryptoFee,392);assert.equal(q.total,25642);
 dom.window.close();
});
